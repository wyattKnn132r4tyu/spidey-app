#!/usr/bin/env node
/**
 * Generates the fixture the Android parity test asserts against.
 *
 * The Android widget re-implements the seeding and confidence maths in Kotlin
 * because RemoteViews cannot run the app's JavaScript. This dumps the reference
 * values from the real TypeScript so the port can be proven equal rather than
 * assumed equal.
 *
 * Run: npm run build:parity
 */
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const bundled = await build({
  entryPoints: [resolve(root, 'widgets/ios/core-entry.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'SpideyCore',
  target: 'es2020',
  platform: 'neutral',
});

const SpideyCore = new Function(`${bundled.outputFiles[0].text}; return SpideyCore;`)();

// Fixed inputs so the fixture is reproducible.
const NOW = 1_760_000_000_000;
const HOME = { lat: 40.7484, lng: -73.9857 };

const sightings = SpideyCore.seedSightings(HOME, NOW);

const rows = sightings.map((s) => ({
  lat: s.lat,
  lng: s.lng,
  createdAt: s.createdAt,
  confirms: s.confirms.length,
  denies: s.denies.length,
  onPatrol: s.reportedOnPatrol,
  confidence: SpideyCore.confidenceOf(s, NOW),
  heat: SpideyCore.heatOf(s, NOW),
}));

const counts = rows.reduce(
  (acc, r) => ({ ...acc, [r.heat]: acc[r.heat] + 1 }),
  { hot: 0, warm: 0, cold: 0 },
);

/** Kotlin reads `123` in a doubleArrayOf as an Int literal, so force a decimal point. */
const d = (value) => {
  const text = String(value);
  return /[.eE]/.test(text) ? text : `${text}.0`;
};

const kotlin = `package com.spidey.tracker.widget

/**
 * GENERATED by scripts/widget-parity-fixture.mjs — do not edit.
 *
 * Reference values produced by the app's own TypeScript. SpideyCoreTest asserts
 * the Kotlin port reproduces them exactly.
 */
object ParityFixture {
    const val NOW = ${NOW}L
    const val HOME_LAT = ${d(HOME.lat)}
    const val HOME_LNG = ${d(HOME.lng)}

    const val HOT = ${counts.hot}
    const val WARM = ${counts.warm}
    const val COLD = ${counts.cold}

    val LAT = doubleArrayOf(
${rows.map((r) => `        ${d(r.lat)},`).join('\n')}
    )

    val LNG = doubleArrayOf(
${rows.map((r) => `        ${d(r.lng)},`).join('\n')}
    )

    val CREATED_AT = doubleArrayOf(
${rows.map((r) => `        ${d(r.createdAt)},`).join('\n')}
    )

    val CONFIRMS = intArrayOf(
${rows.map((r) => `        ${r.confirms},`).join('\n')}
    )

    val DENIES = intArrayOf(
${rows.map((r) => `        ${r.denies},`).join('\n')}
    )

    val CONFIDENCE = doubleArrayOf(
${rows.map((r) => `        ${d(r.confidence)},`).join('\n')}
    )
}
`;

const out = resolve(
  root,
  'android/app/src/test/java/com/spidey/tracker/widget/ParityFixture.kt',
);
await writeFile(out, kotlin, 'utf8');

console.log(`${rows.length} sightings · hot=${counts.hot} warm=${counts.warm} cold=${counts.cold}`);
console.log(`wrote ${out}`);
